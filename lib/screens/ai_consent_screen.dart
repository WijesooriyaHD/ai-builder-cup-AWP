import 'package:cloud_firestore/cloud_firestore.dart';
import 'package:firebase_auth/firebase_auth.dart';
import 'package:flutter/material.dart';
import 'package:google_fonts/google_fonts.dart';

import '../config/legal_links.dart';
import '../services/auth_service.dart';

/// One-time consent before any personal data is sent to a third-party AI
/// (App Store Review Guideline 5.1.2(i)).
///
/// Shown by [AuthWrapper] until the user's document has `ai_data_consent_at`.
/// AI is core to the app, so declining signs the user out rather than leaving
/// them in an app whose features would all silently fail.
class AiConsentScreen extends StatefulWidget {
  const AiConsentScreen({super.key});

  /// Firestore field on `users/{uid}` recording when consent was given.
  static const String consentField = 'ai_data_consent_at';

  @override
  State<AiConsentScreen> createState() => _AiConsentScreenState();
}

class _AiConsentScreenState extends State<AiConsentScreen> {
  bool _saving = false;

  Future<void> _agree() async {
    final uid = FirebaseAuth.instance.currentUser?.uid;
    if (uid == null) return;
    setState(() => _saving = true);
    try {
      // AuthWrapper listens to this document and moves on once it's set.
      await FirebaseFirestore.instance.collection('users').doc(uid).set(
        {AiConsentScreen.consentField: FieldValue.serverTimestamp()},
        SetOptions(merge: true),
      );
    } catch (e) {
      debugPrint('❌ AiConsentScreen: saving consent failed: $e');
      if (!mounted) return;
      setState(() => _saving = false);
      ScaffoldMessenger.of(context).showSnackBar(
        const SnackBar(content: Text('Could not save. Please check your connection and try again.')),
      );
    }
  }

  Future<void> _decline() async {
    final confirmed = await showDialog<bool>(
      context: context,
      builder: (dialogContext) => AlertDialog(
        title: const Text('AI is how the app works'),
        content: const Text(
          "AI Wellness Pal's plans, reflections, coaching and chat are all "
          "generated by AI, so the app can't work without it. If you don't "
          "agree, you'll be signed out. You can come back any time.",
        ),
        actions: [
          TextButton(
            onPressed: () => Navigator.pop(dialogContext, false),
            child: const Text('Go back'),
          ),
          TextButton(
            onPressed: () => Navigator.pop(dialogContext, true),
            child: const Text('Sign out'),
          ),
        ],
      ),
    );
    if (confirmed == true) {
      await AuthService().signOut();
    }
  }

  @override
  Widget build(BuildContext context) {
    final theme = Theme.of(context);
    final muted = theme.colorScheme.onSurface.withOpacity(0.7);

    Widget item(IconData icon, String title, String body) => Padding(
          padding: const EdgeInsets.only(bottom: 16),
          child: Row(
            crossAxisAlignment: CrossAxisAlignment.start,
            children: [
              Icon(icon, size: 22, color: theme.colorScheme.primary),
              const SizedBox(width: 12),
              Expanded(
                child: Column(
                  crossAxisAlignment: CrossAxisAlignment.start,
                  children: [
                    Text(title,
                        style: const TextStyle(fontWeight: FontWeight.w600, fontSize: 15)),
                    const SizedBox(height: 2),
                    Text(body, style: TextStyle(color: muted, height: 1.4)),
                  ],
                ),
              ),
            ],
          ),
        );

    return Scaffold(
      body: SafeArea(
        child: Column(
          children: [
            Expanded(
              child: ListView(
                padding: const EdgeInsets.fromLTRB(24, 32, 24, 16),
                children: [
                  Icon(Icons.auto_awesome_rounded,
                      size: 40, color: theme.colorScheme.primary),
                  const SizedBox(height: 16),
                  Text(
                    'Your data and AI',
                    style: GoogleFonts.outfit(fontSize: 26, fontWeight: FontWeight.w600),
                  ),
                  const SizedBox(height: 8),
                  Text(
                    "AI Wellness Pal uses Google's Gemini AI to create your plans, "
                    'insights and replies. To do that, some of your information is '
                    'sent to Google each time you use an AI feature.',
                    style: TextStyle(color: muted, height: 1.45),
                  ),
                  const SizedBox(height: 24),
                  item(Icons.send_rounded, 'What is shared with Google Gemini',
                      'Your messages and voice conversations with the Pal, journal '
                      'entries you discuss, check-ins and intentions, meal photos and '
                      'descriptions, and sleep summaries if you connect Apple Health.'),
                  item(Icons.shield_outlined, 'How it is used',
                      'Only to generate responses for you. It is never sold or used '
                      'for advertising, and Apple Health data is never used for '
                      'marketing.'),
                  item(Icons.tune_rounded, 'Your control',
                      'You can delete your account and data at any time in '
                      'Settings → Delete Account.'),
                  Align(
                    alignment: Alignment.centerLeft,
                    child: TextButton(
                      style: TextButton.styleFrom(padding: EdgeInsets.zero),
                      onPressed: () => LegalLinks.open(LegalLinks.privacyPolicy),
                      child: const Text('Read the Privacy Policy'),
                    ),
                  ),
                ],
              ),
            ),
            Padding(
              padding: const EdgeInsets.fromLTRB(24, 8, 24, 16),
              child: Column(
                children: [
                  SizedBox(
                    width: double.infinity,
                    child: ElevatedButton(
                      onPressed: _saving ? null : _agree,
                      style: ElevatedButton.styleFrom(
                        padding: const EdgeInsets.symmetric(vertical: 16),
                        shape: RoundedRectangleBorder(
                            borderRadius: BorderRadius.circular(16)),
                      ),
                      child: _saving
                          ? const SizedBox(
                              height: 22,
                              width: 22,
                              child: CircularProgressIndicator(strokeWidth: 2))
                          : const Text('I agree',
                              style: TextStyle(fontWeight: FontWeight.bold)),
                    ),
                  ),
                  TextButton(
                    onPressed: _saving ? null : _decline,
                    child: const Text("Don't agree"),
                  ),
                ],
              ),
            ),
          ],
        ),
      ),
    );
  }
}
